def test_no_renumbered_predecessor_slug_survives_anywhere() -> None:
    """AC5. No `05h`-`05l` slug survives in source or any generated root.

    Renumbering leaves two kinds of debris: a stale source file, and a
    slug-keyed generated output that the pruner missed. OpenCode keys filenames
    on the source slug, so it is the root where a renumber orphan actually
    lands; Claude and Codex key on the stem and survive a renumber with
    filenames intact. All three are checked rather than the one that failed
    before.
    """
    roots = (
        GITHUB_AGENTS_DIR,
        REPO_ROOT / "ports" / "claude" / "agents",
        REPO_ROOT / "ports" / "opencode" / "agents",
        REPO_ROOT / "ports" / "codex" / "agents",
        REPO_ROOT / "ports" / "codex" / "profiles",
    )
    offenders = [
        str(path.relative_to(REPO_ROOT))
        for root in roots
        if root.exists()
        for path in root.iterdir()
        if any(path.name.startswith(slug) for slug in OLD_SLUGS)
    ]
    assert not offenders, "renumbered-predecessor outputs survived: " + ", ".join(
        offenders
    )


def test_roster_propagates_to_all_three_generated_roots() -> None:
    """AC5. Every survivor reaches Claude, OpenCode, and Codex.

    The three roots key filenames differently, which is exactly why a rename is
    able to reach two of them and silently miss the third.
    """
    missing: list[str] = []
    for slug in PR_REVIEW_ROSTER:
        stem = slug.split("-", 1)[1]
        for candidate in (
            REPO_ROOT / "ports" / "claude" / "agents" / f"z-{stem}.md",
            REPO_ROOT / "ports" / "opencode" / "agents" / f"{slug}.md",
            REPO_ROOT / "ports" / "codex" / "agents" / f"z-{stem}.toml",
        ):
            if not candidate.exists():
                missing.append(str(candidate.relative_to(REPO_ROOT)))
    assert not missing, "roster stopped propagating to: " + ", ".join(missing)


