def _changes(counters: dict) -> dict:
    import sys

    sys.path.insert(0, str(REPO_ROOT / "scripts"))
    import propagate_master_assets as mod

    return mod.propagation_changes(counters)


def test_propagation_is_idempotent() -> None:
    """AC8. Two consecutive runs; the second reports zero changes.

    Run against an isolated consumer, so the first run does the real work from
    an empty tree and the second has nothing left to do. That ordering is the
    point: asserting only that a settled tree does not move would pass on a
    propagator that never converges from scratch.
    """
    import shutil
    import tempfile

    import _propagate_env as env

    with tempfile.TemporaryDirectory() as tmp:
        consumer = Path(tmp) / "consumer"
        consumer.mkdir()
        shutil.copytree(REPO_ROOT / "source_of_truth", consumer / "source_of_truth")

        # `propagate_once` reads its source from the redirected `source_of_truth`, so
        # copying the source tree into the consumer is all the isolation this needs.
        with env.redirect(consumer):
            env.mod.propagate_once(verbose=False)
            second = env.mod.propagate_once(verbose=False)

    assert not _changes(second), (
        "a second consecutive propagation run still changed things: "
        f"{_changes(second)}. Propagation must be a fixed-point operation."
    )


def test_committed_tree_is_at_a_propagation_fixed_point() -> None:
    """AC8. The committed generated roots match what the source produces.

    Distinct from idempotency above, and the stronger claim: propagation is
    *not* idempotent across an agent-identifier reclassification. Identifier
    resolution reads on-disk stems, so removing a subagent file changes the
    identifier computed on the next run -- this tree has needed three runs to
    converge. A single run therefore leaves a valid-looking but non-converged
    tree, which is why "I ran the propagator" is not evidence and this asserts
    the settled state instead.

    This writes to the working tree only when it is already wrong, in which case
    the write is the repair and the failure is the report.
    """
    import _propagate_env as env

    counters = env.mod.propagate_once(verbose=False)
    assert not _changes(counters), (
        "the committed tree is not at a propagation fixed point; a run still "
        f"changed things: {_changes(counters)}. Run propagation repeatedly until "
        "every change counter is zero, then commit the result."
    )


