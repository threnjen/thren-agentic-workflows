def test_no_shipped_asset_names_a_retired_skill_or_command() -> None:
    """AC6. The `phase-final-review-*` skill and command names are gone.

    Feature `03` renamed both skill directories and feature `04` regenerated the
    command. A surviving reference points a live agent at a skill that no longer
    exists -- a load failure, not a cosmetic one.

    Swept across every shipped asset root; see `SHIPPED_ASSET_PREFIXES` for why
    that set is an allowlist.
    """
    needles = RETIRED_SKILL_DIRS + (RETIRED_COMMAND,)
    offenders: list[str] = []
    for path in _tracked_files():
        if not _is_shipped_asset(path):
            continue
        try:
            text = _read(path)
        except (UnicodeDecodeError, FileNotFoundError, IsADirectoryError):
            continue
        found = sorted({name for name in needles if name in text})
        if found:
            offenders.append(f"{path}: {', '.join(found)}")
    assert not offenders, "retired skill/command names survive:\n" + "\n".join(
        offenders
    )


