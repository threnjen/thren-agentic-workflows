def test_agents_readme_roster_covers_every_pr_review_evaluator_on_disk() -> None:
    """AC6. The catalogue is derived from disk, not maintained in parallel.

    This closes the second half of a defect whose first half feature `05`
    already closed. At the phase baseline, `expected_slugs` omitted exactly
    `05a`, `05g`, `05j`, `05k` -- and the catalogue's subagent table omitted
    exactly the same four. Feature `05` made omission from `expected_slugs`
    fail; nothing made omission from the catalogue fail, and the defect
    reproduced there (`05a` absent, `05f` still listed under its old `05h`
    slug) while the tested surface stayed correct.

    A restated roster drifts. This derives the expectation from disk so that
    adding an evaluator without cataloguing it fails here.
    """
    catalogue = _read("USAGE.md")
    for slug in PR_REVIEW_ROSTER:
        # Matched as a whole bolded table cell, not as a bare name. A bare
        # `name in catalogue` is satisfied by any superstring, so renaming a row
        # to `Baseline Worktreex` -- or leaving `05f Test Health` listed under a
        # retired slug -- would keep it green. That substring hole is the exact
        # defect this phase keeps rediscovering, and this guard had it until the
        # mutation sweep said so.
        _assert_once(
            catalogue,
            f"| **{_display_name_for(slug)}** |",
            f"agent catalogue row for {slug}",
        )


def _display_name_for(slug: str) -> str:
    """Read an agent's `name:` from its own frontmatter.

    Derived, not restated -- the point of the test above is that a second copy
    of the roster is the defect.
    """
    text = (GITHUB_AGENTS_DIR / f"{slug}.agent.md").read_text(encoding="utf-8")
    frontmatter = text[4:].split("\n---\n", 1)[0]
    for line in frontmatter.splitlines():
        if line.startswith("name:"):
            return line.split(":", 1)[1].strip().strip("\"'")
    raise AssertionError(f"{slug} declares no name:")


