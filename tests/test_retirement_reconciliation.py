DOC_SURFACES = (
    "USAGE.md",
    "docs/CODEBASE_CONTEXT.md",
    "README.md",
)

# The roots that actually ship: authored source assets and their generated
# copies. This is an ALLOWLIST, not an exclusion list, and that direction is
# deliberate. A retired skill or command name is only harmful where something
# loads it -- an agent body pointing at a skill directory that no longer exists
# is a load failure. Those live here and nowhere else.
#
# An exclusion list answers "what may keep the name?", and every false positive
# it produces is closed by appending one more exemption until the sweep no
# longer sweeps. An allowlist answers "where would it hurt?", which does not
# grow under pressure.
#
# `tests/` is outside it for a reason worth stating: a test that asserts a name
# is gone has to write the name down. `test_pr_review_skills.py` holds the
# rename map itself, and `test_readiness_synthesis_agents.py` asserts the old
# skill names are absent from the synthesizer's prose. Sweeping those would fire
# on the guards for the very thing being swept, and the only way to keep it
# green would be to exempt them -- which is how a sweep dies.
SHIPPED_ASSET_PREFIXES = (
    "source_of_truth/agents/",
    "source_of_truth/skills/",
    "source_of_truth/instructions/",
    "ports/claude/",
    "ports/opencode/",
    "ports/codex/",
    "ports/cursor/",
    "ports/github/",
    ".github/",
)

# The propagated copy of an exempt source. Generated, not authored: fixing it
# means editing `source_of_truth/learnings/`, which is an exempt historical record, so
# sweeping it would demand a change the exemption forbids.
GENERATED_EXEMPT_PREFIXES = (
    "ports/claude/learnings/",
    "ports/github/learnings/",
    ".github/learnings/",
    "ports/cursor/rules/",
)


def _is_shipped_asset(path: str) -> bool:
    return path.startswith(SHIPPED_ASSET_PREFIXES) and not path.startswith(
        GENERATED_EXEMPT_PREFIXES
    )


def _tracked_files() -> list[str]:
    listing = subprocess.run(
        ["git", "ls-files", "-z"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return [path for path in listing.split("\0") if path]


def _read(path: str) -> str:
    return (REPO_ROOT / path).read_text(encoding="utf-8")


def _assert_once(haystack: str, needle: str, label: str) -> None:
    """Assert `needle` appears exactly once.

    Exactly-once, not at-least-once. A load-bearing claim that appears twice can
    have its real occurrence deleted while a restatement keeps the test green --
    which is how a guard silently stops guarding. Borrowed from
    `tests/test_readiness_synthesis_agents.py`, where this phase's recurring
    inert-guard defect was diagnosed.
    """
    count = haystack.count(needle)
    assert count == 1, (
        f"{label}: expected exactly 1 occurrence of {needle!r}, found {count}. "
        "Zero means the claim is gone; more than one means this assertion no "
        "longer pins a single load-bearing statement."
    )


def _source_agent_slugs() -> set[str]:
    """Every agent definition on disk, read from the source of truth.

    Two files intentionally lack the `.agent.md` suffix (`prod-code-review.md`
    and `docs-writer.md`) and are still agent definitions, so this globs `*.md`
    and drops the catalogue instead of trusting the suffix.
    """
    return {
        path.name.split(".")[0]
        for path in GITHUB_AGENTS_DIR.glob("*.md")
        if path.name != "README.md"
    }


