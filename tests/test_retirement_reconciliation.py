"""Assembly guard for the PR-Review rescope: feature `08`, the integration point.

Features `01`-`07` each shipped an agent, a skill, or a propagator capability that
passed review in isolation. This module is the standing proof that they compose:
that the roster is exactly seven, that no renumbered predecessor survives anywhere,
that the three documentation surfaces describe the family that actually exists, and
that propagation reaches a fixed point.

Three pattern classes, not one
------------------------------
A sweep built from the agent registry matches slugs and `name:` display names. Both
miss the form that actually survived in the two documentation surfaces: the
unhyphenated prose form, which is neither a slug nor a `name:` value. That is
precisely how it outlived a rename the propagator otherwise rewrites automatically
(`_rewrite_agent_references` keys on the display name).

Renumbering makes display names sharper than slugs here. `05g Artifact Sweeper`
became `05c Artifact Sweeper` while `05g` was reissued to the Readiness
Synthesizer -- so a bare `05g` sweep matches a live agent and proves nothing. The
old names are therefore listed whole, never by prefix.
"""

