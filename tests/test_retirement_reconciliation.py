def _hidden_agent_count() -> int:
    """Count `user-invocable: false` agents, defaulting absent keys to true.

    Mirrors the propagator's own default (`propagate_master_assets.py`), so the
    count means what the harness means by it.
    """
    hidden = 0
    for path in GITHUB_AGENTS_DIR.glob("*.md"):
        if path.name == "README.md":
            continue
        frontmatter = path.read_text(encoding="utf-8")[4:].split("\n---\n", 1)[0]
        if "user-invocable: false" in frontmatter:
            hidden += 1
    return hidden


