def test_gitignore_tracks_the_pr_review_fixture_and_ignores_run_output() -> None:
    """AC6c. The functional half of DD-1: both directions, via real traversal.

    Asserted against what git *does*, not against the rule text, and not with
    `git check-ignore` -- which was the obvious primitive and is wrong twice
    over. It exits 0 when any rule matches *including a negation*, so an
    explicitly un-ignored path is indistinguishable from an ignored one; and its
    per-path pattern matching disagrees with real directory traversal for nested
    paths, so it reports "no rule matched" for a file whose parent directory is
    excluded. A guard built on it passed while both halves of this contract were
    broken, until the mutation sweep exposed it.

    So: the fixture is asserted *tracked* (ground truth -- git already committed
    it), and the run root is asserted invisible to `git status`, which is
    traversal, which is the thing that decides whether dry-run output pollutes a
    commit. The temporary file is the only way to observe traversal; it lands in
    the ignored area under test and is removed unconditionally.
    """
    fixture = "tests/fixtures/pr-review/pinned-diff-range.md"
    tracked = subprocess.run(
        ["git", "ls-files", "--error-unmatch", fixture],
        cwd=REPO_ROOT,
        capture_output=True,
    )
    assert tracked.returncode == 0, (
        f"{fixture} is not tracked -- the pinned fixture cannot be committed, so "
        "the dry run has no reproducible input"
    )

    # The check above reads the index, which `.gitignore` cannot affect: an
    # already-tracked file stays tracked whatever the rules say. It proves the
    # fixture is committed; it proves nothing about whether the rules let
    # the *next* fixture file be added. Only a new path exercises that, so both
    # directions are observed the same way -- through traversal.
    assert _git_sees(
        "tests/fixtures/pr-review/mutation-probe.md", cleanup=None
    ), (
        "a new file under tests/fixtures/pr-review/ is ignored -- the fixture "
        "directory has become untrackable, so the fixture cannot be maintained"
    )
    assert not _git_sees(
        "dev/pr-review/abc1234-20260716T000000Z/readiness-report.md",
        cleanup="dev/pr-review/abc1234-20260716T000000Z",
    ), (
        "dry-run output is visible to git status -- a run would offer its own "
        "reports for commit as repository noise"
    )


def _git_sees(rel_path: str, cleanup: str | None) -> bool:
    """Whether git shows `rel_path` as untracked -- i.e. does not ignore it.

    Creates the file, asks `git status`, removes it (`cleanup` names a directory
    to remove wholesale when the file's parent had to be created). Real traversal
    is the only honest oracle: `git check-ignore` matches patterns per-path and
    reports "no rule matched" for a file whose *parent directory* is excluded, so
    it disagrees with what git actually does for exactly the nested paths this
    contract is about.
    """
    import shutil

    path = REPO_ROOT / rel_path
    assert not path.exists(), f"scratch path {rel_path} already exists"
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("scratch", encoding="utf-8")
        status = subprocess.run(
            ["git", "status", "--porcelain", "--untracked-files=all"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    finally:
        path.unlink(missing_ok=True)
        if cleanup:
            shutil.rmtree(REPO_ROOT / cleanup, ignore_errors=True)

    return rel_path in status


